'use client';

import { useEffect, useState } from 'react';

type Game = 'dice' | 'mines' | 'plinko' | 'crash';
type Result = Record<string, any>;
const API = process.env.NEXT_PUBLIC_API_URL || 'http://localhost:5000/api';

async function call(path: string, body?: unknown) {
  const response = await fetch(`${API}${path}`, {
    method: body === undefined ? 'GET' : 'POST',
    headers: body === undefined ? {} : { 'Content-Type': 'application/json' },
    body: body === undefined ? undefined : JSON.stringify(body),
  });
  const payload = await response.json();
  if (!response.ok) throw new Error(payload.message || 'Game request failed');
  return payload;
}

export default function VeltOriginalsPage() {
  const [game, setGame] = useState<Game>('dice');
  const [busy, setBusy] = useState(false);
  const [error, setError] = useState('');
  const [result, setResult] = useState<Result | null>(null);
  const [history, setHistory] = useState<Result[]>([]);
  const [mineCount, setMineCount] = useState(3);
  const [mineRound, setMineRound] = useState('');
  const [mineStatus, setMineStatus] = useState('not_started');
  const [revealed, setRevealed] = useState<number[]>([]);
  const [mineMultiplier, setMineMultiplier] = useState(1);
  const [crashTarget, setCrashTarget] = useState(2);
  const [diceTarget, setDiceTarget] = useState(50);
  const [diceDirection, setDiceDirection] = useState<'over' | 'under'>('over');

  const refreshHistory = async (selected = game) => {
    try {
      const data = await call(`/originals/history?game=velt-${selected}`);
      setHistory(data.rounds || []);
    } catch { /* History is supplementary; keep the game usable. */ }
  };

  useEffect(() => { refreshHistory(); }, [game]);

  const run = async (fn: () => Promise<any>) => {
    setBusy(true); setError('');
    try {
      const data = await fn();
      setResult(data);
      await refreshHistory();
    } catch (err) {
      setError(err instanceof Error ? err.message : 'Unable to play this practice round');
    } finally { setBusy(false); }
  };

  const rollDice = () => run(() => call('/originals/dice/demo', { target: diceTarget, direction: diceDirection }));

  const startMines = () => run(async () => {
    const data = await call('/originals/mines/demo/start', { mineCount });
    setMineRound(data.roundReference);
    setMineStatus('active');
    setRevealed([]);
    setMineMultiplier(1);
    return data;
  });

  const pickMine = (position: number) => run(async () => {
    const data = await call(`/originals/mines/demo/${mineRound}/pick`, { position });
    setMineStatus(data.status);
    setRevealed(data.revealed || []);
    if (data.multiplier) setMineMultiplier(data.multiplier);
    return data;
  });

  const cashoutMines = () => run(async () => {
    const data = await call(`/originals/mines/demo/${mineRound}/cashout`, {});
    setMineStatus(data.status);
    return data;
  });

  const playPlinko = () => run(() => call('/originals/plinko/demo', { rows: 8 }));
  const playCrash = () => run(() => call('/originals/crash/demo', { cashoutAt: crashTarget }));

  const tabs: { id: Game; label: string }[] = [
    { id: 'dice', label: 'Dice' }, { id: 'mines', label: 'Mines' },
    { id: 'plinko', label: 'Plinko' }, { id: 'crash', label: 'Crash' },
  ];

  return (
    <main className="min-h-screen bg-[#090d16] px-4 py-10 text-white sm:px-8">
      <div className="mx-auto max-w-5xl">
        <div className="flex flex-wrap items-end justify-between gap-4">
          <div>
            <p className="text-xs font-bold uppercase tracking-[0.32em] text-cyan-300">VELT Originals</p>
            <h1 className="mt-2 text-4xl font-black tracking-tight sm:text-5xl">Play the originals.</h1>
            <p className="mt-3 max-w-2xl text-sm text-slate-400">Four server-generated games. Every round is recorded and outcomes are generated by the backend.</p>
          </div>
          <span className="rounded-full border border-amber-400/30 bg-amber-400/10 px-3 py-1.5 text-xs font-semibold text-amber-200">PRACTICE MODE · NO CASH VALUE</span>
        </div>

        <div className="mt-8 flex flex-wrap gap-2 rounded-2xl border border-white/10 bg-white/[0.03] p-2">
          {tabs.map(tab => (
            <button key={tab.id} onClick={() => { setGame(tab.id); setResult(null); setError(''); }}
              className={`rounded-xl px-5 py-3 text-sm font-bold transition ${game === tab.id ? 'bg-cyan-300 text-slate-950' : 'text-slate-300 hover:bg-white/10'}`}>
              {tab.label}
            </button>
          ))}
        </div>

        <section className="mt-5 grid gap-5 lg:grid-cols-[1fr_300px]">
          <div className="rounded-3xl border border-white/10 bg-[#111827] p-5 sm:p-8">
            {game === 'dice' && <div className="text-center">
              <p className="text-sm text-slate-400">Choose over or under. The server generates a 0.00–99.99 result.</p>
              <div className="mx-auto mt-6 flex max-w-sm flex-wrap items-center justify-center gap-3">
                <label className="text-left text-xs text-slate-400">Target
                  <input type="number" min="0.01" max="99.99" step="0.01" value={diceTarget} onChange={e => setDiceTarget(Number(e.target.value))} className="mt-1 block w-28 rounded-lg border border-white/10 bg-slate-900 px-3 py-2 text-center text-white" />
                </label>
                <label className="text-left text-xs text-slate-400">Win when
                  <select value={diceDirection} onChange={e => setDiceDirection(e.target.value as 'over' | 'under')} className="mt-1 block rounded-lg border border-white/10 bg-slate-900 px-3 py-2 text-white"><option value="over">Over target</option><option value="under">Under target</option></select>
                </label>
              </div>
              <div className="mx-auto mt-6 flex h-36 w-36 items-center justify-center rounded-3xl bg-slate-100 text-6xl font-black text-slate-950 shadow-xl">{busy ? '…' : result?.outcome?.roll?.toFixed(2) ?? '—'}</div>
              <p className={`mt-5 text-xl font-bold capitalize ${result?.outcome?.result === 'win' ? 'text-emerald-300' : 'text-slate-200'}`}>{result?.outcome?.result || 'Ready to roll?'}</p>
              {result?.outcome && <p className="mt-1 text-sm text-slate-400">Target {result.outcome.target.toFixed(2)} · {result.outcome.winProbability * 100}% chance · {result.outcome.multiplier}x</p>}
              <button disabled={busy} onClick={rollDice} className="mt-7 rounded-xl bg-cyan-300 px-8 py-3.5 font-extrabold text-slate-950 disabled:opacity-50">{busy ? 'Rolling…' : 'Roll dice'}</button>
            </div>}

            {game === 'mines' && <div>
              <div className="flex flex-wrap items-center justify-between gap-3">
                <div><h2 className="text-2xl font-black">Mines</h2><p className="mt-1 text-sm text-slate-400">Pick safe tiles. The mine layout stays on the server until the round ends.</p></div>
                <div className="rounded-xl bg-black/30 px-4 py-2 text-sm">Practice multiplier <b className="ml-1 text-cyan-300">{mineMultiplier.toFixed(2)}x</b></div>
              </div>
              <div className="mt-5 flex flex-wrap items-center gap-3">
                <label className="text-sm text-slate-300">Mines
                  <select value={mineCount} onChange={e => setMineCount(Number(e.target.value))} className="ml-2 rounded-lg border border-white/10 bg-slate-900 px-3 py-2">
                    {[1,2,3,4,5,8,10,12,15,20,24].map(n => <option key={n} value={n}>{n}</option>)}
                  </select>
                </label>
                <button disabled={busy || mineStatus === 'active'} onClick={startMines} className="rounded-lg bg-cyan-300 px-4 py-2 text-sm font-bold text-slate-950 disabled:opacity-50">New round</button>
                <button disabled={busy || mineStatus !== 'active' || revealed.length === 0} onClick={cashoutMines} className="rounded-lg border border-emerald-400/50 px-4 py-2 text-sm font-bold text-emerald-300 disabled:opacity-40">Cash out practice</button>
              </div>
              <div className="mx-auto mt-6 grid max-w-md grid-cols-5 gap-2">
                {Array.from({ length: 25 }, (_, i) => <button key={i} disabled={busy || mineStatus !== 'active' || revealed.includes(i)} onClick={() => pickMine(i)}
                  className={`aspect-square rounded-xl border text-lg font-black transition ${revealed.includes(i) ? 'border-cyan-300/40 bg-cyan-300/15 text-cyan-200' : 'border-white/10 bg-slate-800 hover:border-cyan-300/70 hover:bg-slate-700 disabled:opacity-50'}`}>
                  {revealed.includes(i) ? (result?.mineHit === i ? '✕' : '◆') : '·'}
                </button>)}
              </div>
              <p className="mt-4 text-center text-sm text-slate-400">Round status: <b className="text-white">{mineStatus.replace('_', ' ')}</b></p>
            </div>}

            {game === 'plinko' && <div className="text-center">
              <h2 className="text-2xl font-black">Plinko</h2><p className="mt-1 text-sm text-slate-400">Eight rows · binomial slot distribution · 99% theoretical return</p>
              <div className="mx-auto mt-8 max-w-lg rounded-2xl bg-slate-950 p-5">
                <div className="flex flex-wrap justify-center gap-2">
                  {(result?.outcome?.path || Array(8).fill(null)).map((direction: number | null, i: number) => <span key={i} className="flex h-8 w-8 items-center justify-center rounded-full bg-slate-800 text-xs text-cyan-200">{direction === null ? '·' : direction ? '↘' : '↙'}</span>)}
                </div>
                <div className="mt-5 flex justify-center gap-1">
                  {[3.82,2.5,1.25,0.9,0.5,0.9,1.25,2.5,3.82].map((m,i) => <span key={i} className={`flex-1 rounded-md px-1 py-3 text-[10px] font-bold ${result?.outcome?.slot === i ? 'bg-cyan-300 text-slate-950' : 'bg-slate-800 text-slate-300'}`}>{m}x</span>)}
                </div>
              </div>
              {result?.outcome && <p className="mt-5 text-2xl font-black text-cyan-300">Slot {result.outcome.slot} · {result.outcome.multiplier}x</p>}
              <button disabled={busy} onClick={playPlinko} className="mt-7 rounded-xl bg-cyan-300 px-8 py-3.5 font-extrabold text-slate-950 disabled:opacity-50">{busy ? 'Dropping…' : 'Drop ball'}</button>
            </div>}

            {game === 'crash' && <div className="text-center">
              <h2 className="text-2xl font-black">Crash</h2><p className="mt-1 text-sm text-slate-400">Choose a target multiplier. The server generates the crash point for each round.</p>
              <div className="mx-auto mt-8 max-w-xs rounded-3xl border border-white/10 bg-slate-950 p-7">
                <p className="text-xs uppercase tracking-widest text-slate-500">Your practice target</p>
                <div className="mt-2 flex items-center justify-center gap-2"><input type="number" min="1.01" max="1000" step="0.01" value={crashTarget} onChange={e => setCrashTarget(Number(e.target.value))} className="w-32 rounded-xl border border-white/10 bg-slate-900 px-3 py-3 text-center text-2xl font-black text-white" /><span className="text-xl text-cyan-300">x</span></div>
                {result?.outcome && <div className="mt-6"><p className="text-xs uppercase text-slate-500">Crash point</p><p className="mt-1 text-4xl font-black text-cyan-300">{result.outcome.crashAt.toFixed(2)}x</p><p className={`mt-2 font-bold ${result.outcome.result === 'cashed_out' ? 'text-emerald-300' : 'text-rose-300'}`}>{result.outcome.result === 'cashed_out' ? `Target reached at ${result.outcome.cashoutAt}x` : 'Busted before target'}</p></div>}
              </div>
              <button disabled={busy} onClick={playCrash} className="mt-7 rounded-xl bg-cyan-300 px-8 py-3.5 font-extrabold text-slate-950 disabled:opacity-50">{busy ? 'Running…' : 'Start crash round'}</button>
            </div>}

            {error && <p className="mt-5 rounded-xl border border-rose-400/30 bg-rose-400/10 p-3 text-sm text-rose-200" role="alert">{error}</p>}
            {result?.roundReference && <p className="mt-5 break-all text-center text-xs text-slate-500">Round reference: {result.roundReference}</p>}
          </div>

          <aside className="rounded-3xl border border-white/10 bg-[#111827] p-5">
            <h3 className="font-extrabold">Recent practice rounds</h3>
            <div className="mt-4 space-y-3">
              {history.length === 0 && <p className="text-sm text-slate-500">No rounds recorded yet.</p>}
              {history.map((round: any) => <div key={round.roundReference} className="rounded-xl bg-slate-950/70 p-3">
                <div className="flex justify-between gap-2 text-xs"><b className="uppercase text-cyan-200">{round.gameCode?.replace('velt-', '')}</b><span className="text-slate-500">{round.createdAt ? new Date(round.createdAt).toLocaleTimeString() : ''}</span></div>
                <p className="mt-1 text-sm text-slate-300">{round.outcome?.result || round.outcome?.status || (round.outcome?.multiplier ? `${round.outcome.multiplier}x` : 'Round')}</p>
                <p className="mt-1 text-[10px] text-slate-600">{round.roundReference}</p>
              </div>)}
            </div>
          </aside>
        </section>

        <p className="mt-6 rounded-2xl border border-amber-400/20 bg-amber-400/[0.06] p-4 text-xs leading-6 text-amber-100/80">
          Practice environment only. No deposits, wagers, cash-outs, prizes or wallet credits are available. The displayed multipliers are game-math demonstrations, not monetary offers. Real-money release requires jurisdiction approval, certified game testing, player-protection controls and a contracted payment provider.
        </p>
      </div>
    </main>
  );
}
